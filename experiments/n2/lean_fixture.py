#!/usr/bin/env python3
"""Generate NoveltyLab/Fixture.lean: a non-associative Cayley-Dickson instance for the Lean oracle.

The fixture carries the 8x8x8 structure tensor of experiments/n2/pentagon.py
over F_P (t[i][j][k] = coefficient of e_k in e_i e_j) and quadruples whose
pentagon edges are nonzero, each with the five edge terms Python computed.
The Lean self-check recomputes every product from the tensor alone and must
reproduce those edges, so the two implementations replay each other.

Cases (all deterministic):
* the first basis quadruple with a nonzero edge (experiment(P)["witness"]);
* SEEDED random quadruples whose five edges are all nonzero and whose
  left/right order mutants (d[a,b,c] for [a,b,c]d, [b,c,d]a for a[b,c,d])
  break the boundary, so a sign or order error in any Lean term fails.

Usage: lean_fixture.py [--check]
"""
from __future__ import annotations

import random
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import pentagon as P5  # noqa: E402

OUT = HERE.parents[1] / "NoveltyLab" / "Fixture.lean"
P, DIM, SEED, DENSE = 5, 8, 20261001, 2
ZERO = (0,) * DIM


def table(p: int = P) -> list[list[list[int]]]:
    bs = P5.basis(DIM)
    return [[list(P5.mul(bs[i], bs[j], p)) for j in range(DIM)] for i in range(DIM)]


def order_mutants(a, b, c, d, p: int = P) -> tuple[tuple, tuple]:
    """Boundary sums with [a,b,c]d -> d[a,b,c] and with a[b,c,d] -> [b,c,d]a."""
    t = list(P5.boundary_terms(a, b, c, d, p))
    swaps = ((0, P5.mul(d, P5.assoc(a, b, c, p), p)), (2, P5.mul(P5.assoc(b, c, d, p), a, p)))
    return tuple(_sum(t[:i] + [term] + t[i + 1:], p) for i, term in swaps)


def _sum(vs, p: int):
    total = ZERO
    for v in vs:
        total = P5.add(total, v, p)
    return total


def discriminating(q, p: int = P) -> bool:
    return all(any(e) for e in P5.boundary_terms(*q, p)) and all(any(m) for m in order_mutants(*q, p))


def cases(p: int = P) -> list[tuple[tuple, bool]]:
    witness = P5.experiment(p)["witness"][:4]
    rng, dense = random.Random(SEED), []
    while len(dense) < DENSE:
        q = tuple(tuple(rng.randrange(p) for _ in range(DIM)) for _ in range(4))
        if discriminating(q, p):
            dense.append(q)
    return [(witness, discriminating(witness, p))] + [(q, True) for q in dense]


def lean_vec(v) -> str:
    return "#[" + ", ".join(map(str, v)) + "]"


def render() -> str:
    rows = ",\n".join("    #[" + ", ".join(lean_vec(cell) for cell in row) + "]" for row in table())
    blocks = []
    for (a, b, c, d), disc in cases():
        edges = ", ".join(lean_vec(e) for e in P5.boundary_terms(a, b, c, d, P))
        blocks.append(f"  {{ a := {lean_vec(a)}, b := {lean_vec(b)}, c := {lean_vec(c)}, d := {lean_vec(d)},\n"
                      f"    edges := #[{edges}],\n    discriminating := {'true' if disc else 'false'} }}")
    case_block = ",\n".join(blocks)
    return f"""-- Generated by experiments/n2/lean_fixture.py from experiments/n2/pentagon.py; do not edit.
-- Regenerate: python experiments/n2/lean_fixture.py
import NoveltyLab.Oracle

namespace NoveltyLab.Fixture

open NoveltyLab.Oracle

/-- The modulus of every fixture computation. -/
def prime : Nat := {P}

/-- Structure tensor of the Cayley-Dickson octonions with parameters (-1, -1, -1) over F_{P}:
`cayleyDickson8[i][j][k]` is the coefficient of e_k in e_i e_j. -/
def cayleyDickson8 : MulTable := #[
{rows}
  ]

/-- A pentagon input and the five edge terms the Python experiment computed for it.
`discriminating` cases have all edges nonzero and order mutants that break the boundary. -/
structure Case where
  a : Vec
  b : Vec
  c : Vec
  d : Vec
  edges : Array Vec
  discriminating : Bool

def cases : Array Case := #[
{case_block}
  ]

end NoveltyLab.Fixture
"""


def main(argv: list[str]) -> int:
    text = render()
    if argv[1:] == ["--check"]:
        current = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("OK: Lean fixture is current" if current else f"stale: {OUT}")
        return 0 if current else 1
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
